def make_options(correct_answer, distractors):
    """Create A/B/C/D options with randomized correct position."""
    labels = ["A", "B", "C", "D"]
    correct_position = random.randint(0, 3)

    options = []
    d_idx = 0
    for i in range(4):
        if i == correct_position:
            options.append(f"{labels[i]}. {correct_answer}")
        else:
            options.append(f"{labels[i]}. {distractors[d_idx]}")
            d_idx += 1

    answer = f"{labels[correct_position]}. {correct_answer}"
    return options, answer


def main():
    with open(INPUT, "r", encoding="utf-8") as f:
        data = json.load(f)

    fb_ids = [q["id"] for q in data if q["type"] == "fill_blank"]
    sc_count = sum(1 for q in data if q["type"] == "single_choice")
    print(f"Before: {len(fb_ids)} fill_blank, {sc_count} single_choice, {len(data)} total")

    converted = 0
    skipped = []
    for q in data:
        if q["type"] != "fill_blank":
            continue

        qid = q["id"]
        if qid not in DISTRACTOR_MAP:
            skipped.append(qid)
            continue

        correct = q["answer"]
        distractors = DISTRACTOR_MAP[qid]

        for i, d in enumerate(distractors):
            if d == correct:
                print(f"  ERROR: {qid} distractor #{i} identical to correct!")

        options, answer = make_options(correct, distractors)
        q["type"] = "single_choice"
        q["options"] = options
        q["answer"] = answer
        converted += 1

    if skipped:
        print(f"  WARNING: {len(skipped)} questions not in map: {skipped}")

    new_fb = sum(1 for q in data if q["type"] == "fill_blank")
    new_sc = sum(1 for q in data if q["type"] == "single_choice")
    print(f"\nAfter: {new_fb} fill_blank, {new_sc} single_choice, {len(data)} total")
    print(f"Converted: {converted}")

    bad = [q["id"] for q in data if q["type"] == "single_choice" and len(q["options"]) != 4]
    if bad:
        print(f"ERROR: Questions with wrong option count: {bad}")
    else:
        print("All single_choice questions have 4 options. OK.")

    dupes = []
    for q in data:
        if q["type"] == "single_choice":
            if len(set(q["options"])) != len(q["options"]):
                dupes.append(q["id"])
    if dupes:
        print(f"WARNING: Duplicate options in: {dupes}")
    else:
        print("No duplicate options. OK.")

    bad_answer = []
    for q in data:
        if q["type"] == "single_choice":
            if q["answer"] not in q["options"]:
                bad_answer.append(q["id"])
    if bad_answer:
        print(f"ERROR: Answer not in options for: {bad_answer}")
    else:
        print("All answers found in options. OK.")

    positions = {"A": 0, "B": 0, "C": 0, "D": 0}
    for q in data:
        if q["type"] == "single_choice" and q["answer"].startswith(("A.", "B.", "C.", "D.")):
            positions[q["answer"][0]] += 1
    print(f"Answer distribution: {positions}")

    print("\n=== Sample results ===")
    sample_ids = ["jc_poetry_001", "jc_poetry_005", "jc_poetry_wb_u_003", "jc_poetry_wb_j3_005"]
    for q in data:
        if q["id"] in sample_ids:
            print(f"\n{q['id']}:")
            for opt in q["options"]:
                print(f"  {opt[:100]}{'...' if len(opt)>100 else ''}")
            print(f"  answer: {q['answer'][:100]}")

    with open(INPUT, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"\nWritten to {INPUT}")


if __name__ == "__main__":
    main()
