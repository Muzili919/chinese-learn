def main():
    total_added = 0
    total_skipped = 0
    total_questions = 0
    file_stats = {}

    for category, filepath in FILES.items():
        if not os.path.exists(filepath):
            print(f"[WARNING] File not found: {filepath}")
            continue

        with open(filepath, "r", encoding="utf-8") as f:
            questions = json.load(f)

        added = 0
        skipped = 0
        missing_explanation = []

        for q in questions:
            total_questions += 1
            qid = q.get("id", "")

            if "explanation" in q and q["explanation"]:
                skipped += 1
                continue

            if qid in EXPLANATIONS:
                q["explanation"] = EXPLANATIONS[qid]
                added += 1
            else:
                # 没有预设解析的题目，使用 analysis 作为 fallback
                analysis = q.get("analysis", "")
                if analysis:
                    q["explanation"] = analysis
                    added += 1
                else:
                    q["explanation"] = "根据题意逐步推导即可。"
                    added += 1
                    missing_explanation.append(qid)

        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(questions, f, ensure_ascii=False, indent=2)

        total_added += added
        total_skipped += skipped
        file_stats[category] = {
            "total": len(questions),
            "added": added,
            "skipped": skipped,
            "missing": missing_explanation,
        }

        print(f"\n[{category}] {filepath}")
        print(f"  Total: {len(questions)}, Added: {added}, Skipped: {skipped}")
        if missing_explanation:
            print(f"  Missing preset explanation (used fallback): {missing_explanation}")

    print("\n" + "=" * 60)
    print(f"SUMMARY")
    print(f"  Total questions processed: {total_questions}")
    print(f"  Explanations added: {total_added}")
    print(f"  Already had explanation: {total_skipped}")
    print("=" * 60)

    # Verify all questions now have explanation
    missing_count = 0
    for category, filepath in FILES.items():
        if not os.path.exists(filepath):
            continue
        with open(filepath, "r", encoding="utf-8") as f:
            questions = json.load(f)
        for q in questions:
            if "explanation" not in q or not q["explanation"]:
                print(f"  [MISSING] {q.get('id', 'unknown')}")
                missing_count += 1

    if missing_count == 0:
        print("\nAll questions now have the 'explanation' field!")
    else:
        print(f"\n{missing_count} questions still missing explanation.")


if __name__ == "__main__":
    main()
