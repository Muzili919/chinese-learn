def ln(x1,y1,x2,y2,s="#2d3748",w=2):
    return '<line x1="'+str(x1)+'" y1="'+str(y1)+'" x2="'+str(x2)+'" y2="'+str(y2)+'" stroke="'+s+'" stroke-width="'+str(w)+'"/>'

def pg(pts,f="none",s="#2d3748",w=2):
    return '<polygon points="'+','.join(str(a)+','+str(b) for a,b in pts)+'" fill="'+f+'" stroke="'+s+'" stroke-width="'+str(w)+'"/>'

def circ(cx,cy,r,f="none",s="#2d3748",w=2):
    return '<circle cx="'+str(cx)+'" cy="'+str(cy)+'" r="'+str(r)+'" fill="'+f+'" stroke="'+s+'" stroke-width="'+str(w)+'"/>'

def dot(cx,cy,r=4,f="#2d3748"):
    return '<circle cx="'+str(cx)+'" cy="'+str(cy)+'" r="'+str(r)+'" fill="'+f+'"/>'

def arc(cx,cy,r,a1,a2,c="#3b82f6",w=1.5):
    x1=cx+r*math.cos(math.radians(a1))
    y1=cy+r*math.sin(math.radians(a1))
    x2=cx+r*math.cos(math.radians(a2))
    y2=cy+r*math.sin(math.radians(a2))
    lg = 1 if (a2-a1) > 180 else 0
    return '<path d="M'+str(round(x1,1))+','+str(round(y1,1))+' A'+str(r)+','+str(r)+' 0 '+str(lg)+',1 '+str(round(x2,1))+','+str(round(y2,1))+'" fill="none" stroke="'+c+'" stroke-width="'+str(w)+'"/>'

def rmk(x,y,sz=12,a=0,c="#ef4444"):
    d=sz*math.cos(math.radians(a))
    e=sz*math.sin(a)
    p=-sz*math.sin(a)
    q=sz*math.cos(a)
    return '<polyline points="'+str(round(x+d,1))+','+str(round(y+e,1))+' '+str(round(x+d+p,1))+','+str(round(y+e+q,1))+' '+str(round(x+p,1))+','+str(round(y+q,1))+'" fill="none" stroke="'+c+'" stroke-width="1.5"/>'

