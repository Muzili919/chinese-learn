def arc(cx,cy,r,a1,a2,c="#3b82f6",w=1.5):
    import math as m
    x1=cx+r*m.cos(m.radians(a1));y1=cy+r*m.sin(m.radians(a1))
    x2=cx+r*m.cos(m.radians(a2));y2=cy+r*m.sin(m.radians(a2))
    lg=1 if (a2-a1)>180 else 0
    return f'<path d="M{x1:.1f},{y1:.1f} A{r},{r} 0 {lg},1 {x2:.1f},{y2:.1f}" fill="none" stroke="{c}" stroke-width={w}/>'
def rmk(x,y,sz=12,a=0,c="#ef4444"):
    import math as m
    d=sz*m.cos(m.radians(a));e=sz*m.sin(a);p=-sz*m.sin(a);q=sz*m.cos(a)
    return f'<polyline points="{x+d:.1f},{y+e:.1f} {x+d+p:.1f},{y+e+q:.1f} {x+p:.1f},{y+q:.1f}" fill="none" stroke="{c}" stroke-width="1.5"/>'
def rect(x,y,w,h,f,st): return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{f}" stroke="{st}" stroke-width="2"/>'

