def get_phonetic(word_key: str) -> str:
    """Get IPA transcription for a word."""
    w = word_key.lower().strip()

    # Direct lookup
    if w in IPA_DICT:
        return IPA_DICT[w]

    # Handle slash variants like "Internet/internet" or "email/e-mail"
    if "/" in w:
        parts = w.split("/")
        for p in parts:
            if p.lower().strip() in IPA_DICT:
                return IPA_DICT[p.lower().strip()]
        # Try with hyphens removed
        for p in parts:
            clean = p.lower().strip().replace("-", "")
            if clean in IPA_DICT:
                return IPA_DICT[clean]

    # Handle multi-word phrases
    if " " in w:
        parts = w.split()
        ipa_parts = []
        for p in parts:
            p_lower = p.lower().strip()
            if p_lower in IPA_DICT:
                ipa_parts.append(IPA_DICT[p_lower].strip("/"))
            else:
                ipa_parts.append(p_lower)  # fallback
        return "/" + " ".join(ipa_parts) + "/"

    # Handle hyphenated words
    if "-" in w:
        parts = w.split("-")
        ipa_parts = []
        for p in parts:
            p_lower = p.lower().strip()
            if p_lower in IPA_DICT:
                ipa_parts.append(IPA_DICT[p_lower].strip("/"))
            else:
                ipa_parts.append(p_lower)
        return "/" + " ".join(ipa_parts) + "/"

    return ""


def get_segmentation(word_key: str) -> str:
    """Get word segmentation for memory aid."""
    w = word_key.lower().strip()

    # Direct lookup (case-insensitive)
    for key, val in SEG_DICT.items():
        if key.lower().strip() == w:
            return val

    # Handle slash variants
    if "/" in w:
        parts = w.split("/")
        for p in parts:
            p_clean = p.lower().strip()
            for key, val in SEG_DICT.items():
                if key.lower().strip() == p_clean:
                    return val
        # Just return the first variant as-is
        return parts[0].strip()

    # Multi-word phrases
    if " " in w:
        parts = w.split()
        seg_parts = []
        for p in parts:
            p_lower = p.lower().strip()
            found = False
            for key, val in SEG_DICT.items():
                if key.lower().strip() == p_lower:
                    seg_parts.append(val)
                    found = True
                    break
            if not found:
                seg_parts.append(p_lower)
        return " ".join(seg_parts)

    # Hyphenated words
    if "-" in w:
        parts = w.split("-")
        seg_parts = []
        for p in parts:
            p_lower = p.lower().strip()
            found = False
            for key, val in SEG_DICT.items():
                if key.lower().strip() == p_lower:
                    seg_parts.append(val)
                    found = True
                    break
            if not found:
                seg_parts.append(p_lower)
        return "·".join(seg_parts)

    # Simple syllable guess for unknown single words
    return simple_syllabify(w)


def simple_syllabify(word: str) -> str:
    """
    Simple syllabification for unknown words.
    Uses basic English syllable patterns.
    """
    if not word or len(word) <= 3:
        return word

    # Common suffixes to split off
    suffixes = ["tion", "sion", "ment", "ness", "able", "ible", "ful", "less",
                "ing", "tion", "ence", "ance", "ous", "ive", "al", "ly", "er",
                "or", "ed", "es", "ty"]

    for suf in suffixes:
        if word.endswith(suf) and len(word) > len(suf) + 2:
            root = word[:-len(suf)]
            return f"{root}·{suf}"

    # Vowel-consonant patterns for basic syllable splitting
    vowels = "aeiouy"
    syllables = []
    current = ""
    i = 0
    while i < len(word):
        current += word[i]
        # If we have a consonant after a vowel and there are more chars, might split
        if (i > 0 and i < len(word) - 2 and
            word[i] not in vowels and word[i-1] in vowels and
            word[i+1] in vowels and len(current) > 1):
            syllables.append(current)
            current = ""
        i += 1

    if current:
        syllables.append(current)

    if len(syllables) <= 1:
        return word

    return "·".join(syllables)


def process_file(filepath: str) -> dict:
    """Process a word network JSON file, adding phonetic and segmentation fields."""
    with open(filepath, "r", encoding="utf-8") as f:
        data = json.load(f)

    stats = {"total": 0, "phonetic_added": 0, "segmentation_added": 0, "phonetic_missing": [], "segmentation_missing": []}

    for word_key in data["words"]:
        stats["total"] += 1

        # Add phonetic
        phonetic = get_phonetic(word_key)
        if phonetic:
            data["words"][word_key]["phonetic"] = phonetic
            stats["phonetic_added"] += 1
        else:
            data["words"][word_key]["phonetic"] = ""
            stats["phonetic_missing"].append(word_key)

        # Add segmentation
        seg = get_segmentation(word_key)
        if seg and seg != word_key.lower().strip():
            data["words"][word_key]["segmentation"] = seg
            stats["segmentation_added"] += 1
        elif seg:
            data["words"][word_key]["segmentation"] = seg
            stats["segmentation_added"] += 1
        else:
            data["words"][word_key]["segmentation"] = word_key
            stats["segmentation_missing"].append(word_key)

    # Write back
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    return stats


